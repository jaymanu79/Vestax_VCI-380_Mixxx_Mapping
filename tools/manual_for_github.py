#!/usr/bin/env python3
"""Make the Mixxx manual page readable on GitHub.

The page uses Sphinx roles (:hwlabel:, :guilabel:, :menuselection:) that GitHub,
which renders reStructuredText with plain docutils, doesn't know. This script
declares them as standard docutils roles (bold / italic), and points the figure
to the schematic at the root of this repository.

    python3 tools/manual_for_github.py MANUAL/vestax_vci_380.rst > vestax_vci_380.rst

The input is the page of the manual pull request (mixxxdj/manual), unchanged.
"""
import sys

HEADER = """.. This copy of the Mixxx manual page is generated by tools/manual_for_github.py:
   the Sphinx roles of the manual are declared here so that GitHub can display them.

.. role:: hwlabel(strong)
.. role:: guilabel(strong)
.. role:: menuselection(emphasis)

"""

text = open(sys.argv[1], encoding="utf-8").read()
text = text.replace("../../_static/controllers/vestax_vci_380.svg", "vestax_vci_380.svg")
text = text.replace(" --> ", " > ")
sys.stdout.write(HEADER + text)
